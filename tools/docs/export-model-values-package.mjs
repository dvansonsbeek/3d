#!/usr/bin/env node
/**
 * @essrt/model-values GENERATOR + FRESHNESS CHECK (Phase 14, option a).
 *
 * Renders every registry key (tools/docs/model-values.mjs resolveAll) into
 * packages/model-values/src/model-values.generated.json — the published
 * supply for the website's <V k=…/> tags, published behind the same npm
 * boundary as @essrt/physics.
 *
 *   node tools/docs/export-model-values-package.mjs           check (exit 1 on drift)
 *   node tools/docs/export-model-values-package.mjs --write   regenerate
 *
 * Check mode runs in `npm run check` / check:docs — the packaged values can
 * never silently lag the registry (whose own inputs are protected by the
 * artifact-freshness and data-provenance gates).
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveAll } from './model-values.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'packages', 'model-values', 'src', 'model-values.generated.json');
const WRITE = process.argv.includes('--write');

const modelVersion = JSON.parse(readFileSync(
  join(ROOT, 'public', 'input', 'model-version.json'), 'utf8')).modelVersion;
const coeffSrc = readFileSync(
  join(ROOT, 'packages', 'physics', 'src', 'constants', 'coefficients.js'), 'utf8');
const coefficients = `sha256:${coeffSrc.match(/COEFFICIENTS_HASH = "([0-9a-f]{16})"/)[1]}`;

const resolved = resolveAll();

// Plausibility rows — a published value against the reference it is published
// beside. The identity check below proves only package ≡ registry: model-values
// 16.0.0 shipped periLongModel2000AD 167° off (a private copy of the perihelion
// convention missed the R10 re-origin) while every page's hand-typed "+0.010°"
// delta still read agreement. Keys resolve to rendered strings; compare as numbers.
const PLAUSIBILITY = [
  ['periLongModel2000AD', 'periLongJ2000', 0.02, '° — the model\'s J2000 perihelion vs the IAU mean element'],
];
const asNumber = (s) => Number(String(s).replace(/[,  \s]/g, '').replace(/[−–]/g, '-'));
// fail-proof: ESSRT_VALUES_PLANT=1 re-injects the 16.0.0 offset on the first row.
const plant = process.env.ESSRT_VALUES_PLANT === '1' ? 167.048 : 0;
const implausible = PLAUSIBILITY.filter(([k, ref, tol], i) => !(Math.abs(asNumber(resolved.get(k)) + (i === 0 ? plant : 0) - asNumber(resolved.get(ref))) <= tol));
if (implausible.length) {
  for (const [k, ref, tol, what] of implausible) console.error(`FAIL — implausible registry value: ${k} = ${resolved.get(k)} vs ${ref} = ${resolved.get(ref)} (tolerance ${tol}${what})`);
  process.exit(1);
}

const values = Object.fromEntries([...resolved.entries()].sort(([a], [b]) => a.localeCompare(b)));
const doc = {
  _meta: {
    _comment: 'GENERATED by tools/docs/export-model-values-package.mjs --write from the 3d model-values registry. Do not hand-edit; the check chain compares this file to the live registry on every run.',
    modelVersion,
    coefficients,
    keyCount: resolved.size,
  },
  values,
};
const rendered = JSON.stringify(doc, null, 2) + '\n';

if (WRITE) {
  writeFileSync(OUT, rendered);
  console.log(`✓ wrote ${resolved.size} keys -> packages/model-values/src/model-values.generated.json (${modelVersion}, ${coefficients})`);
  // §10 stamping authority: a refit that regenerates the packaged values
  // also re-stamps both doc trees, so neither can sit at a superseded
  // coefficients hash.
  const { execFileSync } = await import('node:child_process');
  const out = execFileSync('node', [join(ROOT, 'tools', 'docs', 'stamp-frontmatter.mjs'), '--write', '--holistic'], {
    cwd: ROOT, encoding: 'utf8',
  });
  for (const l of out.trimEnd().split('\n')) console.log(`  ${l}`);
} else {
  if (!existsSync(OUT)) {
    console.error('FAIL — package values missing. Generate: node tools/docs/export-model-values-package.mjs --write');
    process.exit(1);
  }
  const current = readFileSync(OUT, 'utf8');
  if (current !== rendered) {
    const prev = JSON.parse(current);
    const drifted = Object.keys(values).filter((k) => prev.values[k] !== values[k]);
    const missing = Object.keys(values).filter((k) => !(k in prev.values));
    const extra = Object.keys(prev.values).filter((k) => !(k in values));
    console.error(`FAIL — @essrt/model-values lags the registry (${drifted.length} drifted, ${missing.length} new, ${extra.length} stale keys).`);
    for (const k of drifted.slice(0, 8)) console.error(`  DRIFT ${k}: packaged "${prev.values[k]}" vs registry "${values[k]}"`);
    console.error('Regenerate: node tools/docs/export-model-values-package.mjs --write');
    process.exit(1);
  }
  console.log(`PASS — @essrt/model-values ≡ registry (${resolved.size} keys, ${modelVersion}, ${coefficients}).`);
}

const model = createModel(DEFAULT_CONSTANTS);
const K = DEFAULT_CONSTANTS;
const D2R = Math.PI / 180;
const LP = K.moon.moonMeeusLpCorrection;
const BRIDGE = K.earthOrbital.deltaTStart / 86400;
const NU = K.physicalConstants.nutationLeadingTermsArcsec;

// Meeus argument polynomials (regressor phases only — precision is
// irrelevant at the regressor level)
function meeusArgs(T) {
  const w = (x) => ((x % 360) + 360) % 360;
  return {
    D: w(297.8501921 + 445267.1114034 * T - 0.0018819 * T * T),
    M: w(357.5291092 + 35999.0502909 * T - 0.0001536 * T * T),
    Mp: w(134.9633964 + 477198.8675055 * T + 0.0087414 * T * T),
    F: w(93.2720950 + 483202.0175233 * T - 0.0036539 * T * T),
  };
}

const rows = [];
for (const [jd, jplLonTrue] of DE441) {
  const jb = jd + BRIDGE;
  const om = (NU.omegaNodeJ2000Deg - 360 * (jb - 2451545.0) / K.moonReference.moonNodalPrecessionDaysInputICRF) * D2R;
  const dPsiDeg = (NU.psiOmega * Math.sin(om)) / 3600;
  const fw = model.moon.lonDegAtJD(jb) + LP;
  let d = fw - (jplLonTrue - dPsiDeg);
  d = ((d + 540) % 360) - 180;
  const T = (jb - 2451545.0) / 36525;
  rows.push({ T, y: d * 3600, args: meeusArgs(T) });
}

// least squares: {1, T, T²} + sin/cos(arg)×{1, T} for five leading args
function fit(rows, usePeriodic) {
  const basis = (r) => {
    const b = [1, r.T, r.T * r.T];
    if (usePeriodic) {
      const a = r.args;
      for (const ph of [a.Mp, 2 * a.D - a.Mp, 2 * a.D, a.M, 2 * a.F]) {
        const x = ph * D2R;
        b.push(Math.sin(x), Math.cos(x), r.T * Math.sin(x), r.T * Math.cos(x));
      }
    }
    return b;
  };
  const n = rows.length, p = basis(rows[0]).length;
  const XtX = Array.from({ length: p }, () => new Float64Array(p));
  const Xty = new Float64Array(p);
  for (const r of rows) {
    const b = basis(r);
    for (let i = 0; i < p; i++) {
      Xty[i] += b[i] * r.y;
      for (let j = 0; j < p; j++) XtX[i][j] += b[i] * b[j];
    }
  }
  const A = XtX.map((row, i) => [...row, ...Array.from({ length: p }, (_, j) => (i === j ? 1 : 0))]);
  for (let c = 0; c < p; c++) {
    let piv = c;
    for (let r2 = c + 1; r2 < p; r2++) if (Math.abs(A[r2][c]) > Math.abs(A[piv][c])) piv = r2;
    [A[c], A[piv]] = [A[piv], A[c]];
    const dd = A[c][c];
    for (let j = 0; j < 2 * p; j++) A[c][j] /= dd;
    for (let r2 = 0; r2 < p; r2++) {
      if (r2 === c) continue;
      const f = A[r2][c];
      for (let j = 0; j < 2 * p; j++) A[r2][j] -= f * A[c][j];
    }
  }
  const inv = A.map((row) => row.slice(p));
  const beta = new Float64Array(p);
  for (let i = 0; i < p; i++) for (let j = 0; j < p; j++) beta[i] += inv[i][j] * Xty[j];
  let ss = 0;
  for (const r of rows) {
    const b = basis(r);
    let pred = 0;
    for (let i = 0; i < p; i++) pred += beta[i] * b[i];
    ss += (r.y - pred) ** 2;
  }
  const sigma2 = ss / (n - p);
  return { beta, se: (i) => Math.sqrt(sigma2 * inv[i][i]), rms: Math.sqrt(ss / n) };
}


#!/usr/bin/env node
/**
 * import-constellation-boundaries — Roman's (1987) constellation lookup table as an INPUT (plan 28 §F2).
 *
 * The IAU boundaries are coordinate lines of the B1875 equatorial frame (Delporte 1930). Roman (1987, PASP 99,
 * 695) reduced them to 357 boxes — (RA_low, RA_up) in hours and DE_low in degrees, B1875 — read in order: the
 * first box containing a position names its constellation. VizieR VI/42 (`data`), via the CfA mirror (the
 * Strasbourg host is unreachable from the build machine), pinned by canonical sha256 and cached in the gitignored
 * data/.cache/stars/. Writes public/input/constellation-boundaries.json, read by the ONE home
 * packages/physics/src/sky/ecliptic-constellations.cjs (the scene's zodiac band and the gates alike).
 *
 * Usage: node tools/pipeline/import-constellation-boundaries.js --write [--fetch] [--pin]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..', '..');
const argv = process.argv.slice(2);
if (!argv.includes('--write')) { console.error('Usage: node tools/pipeline/import-constellation-boundaries.js --write [--fetch] [--pin]'); process.exit(1); }

const CACHE = path.join(ROOT, 'data', '.cache', 'stars', 'roman1987-vi42.tsv');
const OUT = path.join(ROOT, 'public', 'input', 'constellation-boundaries.json');
const SOURCE = {
  title: 'Identification of a constellation from a position (Roman 1987, PASP 99, 695) — VizieR VI/42, table "data": the 357 B1875 boxes',
  licence: 'VizieR — free use with citation',
  url: 'https://vizier.cfa.harvard.edu/viz-bin/asu-tsv?-source=VI/42/data&-out.max=unlimited&-out.all',
  sha256: 'de095cffcc09fd553e19f80d2e7cf06a5e0b74585524ba64c89d917ac5ebeb46',
};
const rel = (/** @type {string} */ p) => path.relative(ROOT, p).split(path.sep).join('/');
const canonicalSha256 = (/** @type {string} */ text) => crypto.createHash('sha256').update(text.split('\n').filter((l) => l.trim() && !l.startsWith('#')).sort().join('\n')).digest('hex');

async function main() {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  if (argv.includes('--fetch') || !fs.existsSync(CACHE)) {
    console.log('fetching VI/42 …');
    const res = await fetch(SOURCE.url, { headers: { 'User-Agent': 'essrt-import/1.0' } });
    if (!res.ok) throw new Error(`fetch VI/42: HTTP ${res.status}`);
    fs.writeFileSync(CACHE, Buffer.from(await res.arrayBuffer()));
  }
  const text = fs.readFileSync(CACHE, 'utf8');
  const sha = canonicalSha256(text);
  const first = /^0+$/.test(SOURCE.sha256) || argv.includes('--pin');
  if (!first && sha !== SOURCE.sha256) throw new Error(`${rel(CACHE)}: canonical sha256 ${sha} ≠ the recorded ${SOURCE.sha256} — the source changed; re-measure before importing (or --pin to adopt)`);
  // VizieR asu-tsv: '#' comments, a header line, a units line, a dashes line, then tab-separated rows
  const lines = text.split('\n').filter((l) => l.length && !l.startsWith('#'));
  const header = lines[0].split('\t').map((s) => s.trim());
  const ci = Object.fromEntries(header.map((h, i) => [h, i]));
  for (const c of ['recno', 'RA_low', 'RA_up', 'DE_low', 'const']) if (!(c in ci)) throw new Error(`VI/42: column ${c} missing (${header.join(', ')})`);
  const boxes = [];
  for (const l of lines.slice(3)) {
    const c = l.split('\t').map((s) => s.trim());
    if (c.length < header.length) continue;
    boxes.push({ recno: Number(c[ci.recno]), raLowHours: Number(c[ci.RA_low]), raUpHours: Number(c[ci.RA_up]), decLowDeg: Number(c[ci.DE_low]), abbr: c[ci.const] });
  }
  boxes.sort((a, b) => a.recno - b.recno);   // Roman's order IS the algorithm (the first matching box wins)
  if (boxes.length !== 357) throw new Error(`VI/42: ${boxes.length} boxes read, Roman's table has 357`);
  const abbrs = new Set(boxes.map((b) => b.abbr));
  const doc = {
    _meta: {
      _comment: 'Roman 1987\'s constellation lookup table — GENERATED by tools/pipeline/import-constellation-boundaries.js --write (plan 28 §F2). The 357 B1875 boxes in Roman\'s order: for a position precessed to B1875, the FIRST box with Dec ≥ decLowDeg and raLowHours ≤ RA < raUpHours names the constellation (the IAU boundaries of Delporte 1930 as coordinate lines; the same table astropy\'s get_constellation reads). ONE home for the lookup: packages/physics/src/sky/ecliptic-constellations.cjs.',
      generated_by: 'tools/pipeline/import-constellation-boundaries.js --write',
      version: 1,
      frame: 'equatorial B1875 (RA in hours, Dec in degrees)',
      counts: { boxes: boxes.length, constellations: abbrs.size },
      source: { ...SOURCE, sha256: undefined, file: rel(CACHE), sha256Canonical: sha, bytes: Buffer.byteLength(text) },
    },
    boxes: boxes.map(({ raLowHours, raUpHours, decLowDeg, abbr }) => ({ raLowHours, raUpHours, decLowDeg, abbr })),
  };
  fs.writeFileSync(OUT, JSON.stringify(doc, null, 1) + '\n');
  console.log(`wrote ${rel(OUT)}: ${boxes.length} boxes, ${abbrs.size} constellations`);
  if (SOURCE.sha256 !== sha) console.log(`  pin: sha256 '${sha}'`);
}
main().catch((e) => { console.error(e.message || e); process.exit(1); });

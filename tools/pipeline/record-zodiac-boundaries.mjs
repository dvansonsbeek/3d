#!/usr/bin/env node
/**
 * record-zodiac-boundaries — the zodiac band of date's referee RECORD (plan 28 §F2, doc 111 §1.48). A generator: writes.
 *
 * The scene is the reference for the ecliptic OF DATE (R4: the placed Earth frame's equinox and ecliptic pole), so
 * this script drives the built simulator headlessly (the browser harness, as the gates do), lands at the epochs,
 * reads the scene's frame (two equatorial-J2000 unit vectors) and the crossings it solved (ONE home
 * @essrt/physics sky/ecliptic-constellations), samples the ecliptic of date every degree (J2000 α, δ and the
 * solver's constellation) with the straddle points a thousandth of a degree either side of every crossing, and
 * writes data/zodiac-boundary-reference.json with its inputs (the boundary table's sha256, the model version).
 * Then scripts/zodiac_boundary_reference.py --write adds astropy's get_constellation for every sample and straddle
 * point (CI has no astropy: the record is generated by hand), and tools/verify/star-catalogue.js reads both.
 *
 * Usage: node tools/pipeline/record-zodiac-boundaries.mjs --write      (needs `npm run build` first)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { openSimulator } from '../../test/browser/harness.mjs';

const require = createRequire(import.meta.url);
const ROOT = new URL('../../', import.meta.url);
const WRITE = process.argv.includes('--write');
if (!WRITE) { console.error('Usage: node tools/pipeline/record-zodiac-boundaries.mjs --write'); process.exit(1); }

const E = require('../../packages/physics/src/sky/ecliptic-constellations.cjs');
const tableRaw = readFileSync(new URL('public/input/constellation-boundaries.json', ROOT), 'utf8');
E.setBoundaryTable(JSON.parse(tableRaw));
const modelVersion = JSON.parse(readFileSync(new URL('public/input/model-version.json', ROOT), 'utf8'));

const EPOCHS = [['2000 d172', 2000], ['-3000 d172', -3000], ['3000 d172', 3000], ['-10000 d172', -10000], ['10000 d172', 10000], ['-100000 d172', -100000], ['-1000000 d172', -1000000]];

const sim = await openSimulator();
const epochs = [];
try {
  await sim.page.waitForFunction(() => window.__test__ && window.__test__.skyLoaded && window.__test__.skyLoaded(), null, { timeout: 120000 });
  await sim.page.waitForFunction(() => window.__test__.zodiacBandProbe().ready, null, { timeout: 60000 });
  for (const [label, nominal] of EPOCHS) {
    // land twice, so a lazily updated element of the Earth frame's placement has settled before the read; between
    // separate runs the frame still differs by ~6e-7 (0.1″), the browser gate's tolerance — the Node gate's bit-for-bit
    // row is the solver on the RECORDED frame
    for (let pass = 0; pass < 2; pass++) {
      await sim.page.evaluate((y) => { window.__test__.enterYearOfDate(y, '00:00:00'); window.__test__.skyUpdate(true); }, label);
      await sim.page.waitForTimeout(800);
    }
    const p = await sim.page.evaluate(() => { const P = window.__test__.zodiacBandProbe(); return { year: P.year, frame: P.frame, crossings: P.crossings }; });
    if (!p.crossings) throw new Error(`${label}: no crossings (regime or table)`);
    // the record's own re-solve on the recorded frame must reproduce the scene's crossings bit for bit
    const again = E.eclipticCrossings(p.frame.pole, p.frame.equinox);
    if (JSON.stringify(again) !== JSON.stringify(p.crossings)) throw new Error(`${label}: the solver on the recorded frame differs from the scene's crossings`);
    const f = E.eclipticFrame(p.frame.pole, p.frame.equinox);
    const samples = [];
    for (let lon = 0; lon < 360; lon += 1) { const v = E.eclipticPointJ2000(f, lon); const rd = E.raDecOfVector(v); samples.push({ lonDeg: lon, raDeg: rd.raDeg, decDeg: rd.decDeg, abbr: E.constellationOfVectorJ2000(v) }); }
    epochs.push({ label, nominalYear: nominal, engineYear: p.year, frame: p.frame, crossings: p.crossings, samples });
    console.log(`${label}: engine year ${p.year.toFixed(3)}, ${p.crossings.length} crossings — ${p.crossings.map((c) => `${c.abbr} ${c.lonDeg.toFixed(3)}`).join(', ')}`);
  }
} finally { await sim.dispose(); }

const doc = {
  _description: 'The zodiac band of date\'s referee record (plan 28 §F2) — GENERATED by tools/pipeline/record-zodiac-boundaries.mjs --write from the built scene (the ecliptic of date is the scene\'s placed Earth frame, R4), the astropy block added by scripts/zodiac_boundary_reference.py --write. Per epoch: the ecliptic of date\'s pole and equinox (equatorial J2000 unit vectors), the crossings the one home solved on them (the IAU boundaries as Roman 1987\'s B1875 boxes), and a sample every degree of ecliptic longitude (J2000 α, δ, the solver\'s constellation). Gate: tools/verify/star-catalogue.js (the solver on the recorded frames ≡ the recorded crossings bit for bit; astropy\'s name ≡ the solver\'s at every sample; astropy\'s own boundary, bisected along the same ecliptic, within 25″ of every crossing — its geocentric frame carries the annual aberration).',
  generated_by: 'tools/pipeline/record-zodiac-boundaries.mjs --write; scripts/zodiac_boundary_reference.py --write',
  inputs: { 'public/input/constellation-boundaries.json': { sha256: createHash('sha256').update(tableRaw).digest('hex') }, modelVersion: modelVersion.version || modelVersion, sampleStepDeg: 1 },
  epochs,
};
writeFileSync(new URL('data/zodiac-boundary-reference.json', ROOT), JSON.stringify(doc, null, 1) + '\n');
console.log(`wrote data/zodiac-boundary-reference.json: ${epochs.length} epochs, ${epochs.reduce((s, e) => s + e.samples.length, 0)} samples — now: python3 scripts/zodiac_boundary_reference.py --write`);

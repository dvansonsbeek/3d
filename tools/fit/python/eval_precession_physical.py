#!/usr/bin/env python3
"""
PHYSICAL-BEAT EVALUATION SCRIPT (§12h follow-up item 6)
=======================================================

Scores the SHIPPED `PREDICT_COEFFS_PHYSICAL` arrays against the training
data — evaluation, NOT a refit. Exists because the website's per-planet
R²/RMSE literals were historical fit-run values predating the J/S
perihelion reframe (their stale term counts were caught by the §12h parity
harness; the stats were never re-measured). This script makes the stats a
generated artifact so the registry derives them and a future refit flows
through.

Same data path as train_precession_physical.py (the Excel fluctuation
columns, downsampled by stepYears), same feature basis
(predictive_formula_physical) — the only difference is that the weights are
READ from public/input/fitted-coefficients.json instead of solved.

Usage:
    cd tools/fit/python
    python eval_precession_physical.py             # print stats
    python eval_precession_physical.py --write     # + write data/planet-prediction-fit-stats.json
"""

import argparse
import json
import math
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parent.parent.parent
sys.path.insert(0, str(_ROOT / 'tools' / 'lib' / 'python'))
sys.path.insert(0, str(_HERE))

from predictive_formula_physical import build_features_physical  # noqa: E402
from train_precession_physical import load_excel_data, PLANET_NAMES  # noqa: E402

EXCEL_PATH = _ROOT / 'data' / '01-holistic-year-objects-data.xlsx'
COEFFS_PATH = _ROOT / 'public' / 'input' / 'fitted-coefficients.json'
OUT_PATH = _ROOT / 'data' / 'planet-prediction-fit-stats.json'


def evaluate(planet_key, rows, coeffs):
    years = [y for y, _ in rows]
    target = np.array([v for _, v in rows])
    X = np.array([build_features_physical(y, PLANET_NAMES[planet_key]) for y in years])
    w = np.array(coeffs)
    if X.shape[1] != w.shape[0]:
        raise SystemExit(
            f'{planet_key}: feature count {X.shape[1]} != shipped coefficient count {w.shape[0]} — '
            'the basis and the shipped arrays have desynced; re-run the trainer.')
    pred = X @ w
    residuals = target - pred
    n = len(years)
    ss_res = float(np.sum(residuals ** 2))
    ss_tot = float(np.sum((target - np.mean(target)) ** 2))
    return {
        'n_samples': n,
        'terms': int(w.shape[0]),
        'rmse_arcsec_cy': math.sqrt(ss_res / n),
        'r2': 1 - (ss_res / ss_tot) if ss_tot > 0 else 0.0,
    }


def main():
    parser = argparse.ArgumentParser(description='Evaluate the SHIPPED physical-beat coefficients (no refit).')
    parser.add_argument('--write', action='store_true', help=f'write {OUT_PATH.relative_to(_ROOT)}')
    args = parser.parse_args()

    print(f'Loading {EXCEL_PATH.name} ...')
    data = load_excel_data(EXCEL_PATH)
    shipped = json.loads(COEFFS_PATH.read_text())['PREDICT_COEFFS_PHYSICAL']

    try:
        git_sha = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=_ROOT,
                                 capture_output=True, text=True).stdout.strip()
    except OSError:
        git_sha = 'unknown'

    result = {
        '_description': (
            'R2/RMSE of the SHIPPED PREDICT_COEFFS_PHYSICAL arrays scored against the training '
            'fluctuation data (evaluation, not a refit) — generated by '
            'tools/fit/python/eval_precession_physical.py --write. Consumed by the model-values '
            'registry (*PredR2/*PredRmse keys). Re-run after any physical-beat retrain.'),
        'generated': datetime.now(timezone.utc).isoformat(),
        'git_sha': git_sha,
        'planets': {},
    }
    for planet in PLANET_NAMES:
        stats = evaluate(planet, data[planet], shipped[planet])
        result['planets'][planet] = stats
        print(f'  {planet:8s}  n={stats["n_samples"]:5d}  terms={stats["terms"]}  '
              f'RMSE={stats["rmse_arcsec_cy"]:.4f} "/cy  R2={stats["r2"]:.6f}')

    if args.write:
        OUT_PATH.write_text(json.dumps(result, indent=2) + '\n')
        print(f'\n  wrote {OUT_PATH.relative_to(_ROOT)}')
    else:
        print('\n  dry run — pass --write to update the artifact')


if __name__ == '__main__':
    main()

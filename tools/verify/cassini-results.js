#!/usr/bin/env node
/**
 * CASSINI MOONTILT RESULTS GENERATOR (§12h follow-up item 4)
 * ==========================================================
 *
 * Owns `data/cassini-moontilt-results.json`. Runs BOTH Cassini labs with
 * their --json result lines and writes the artifact from their live output —
 * the file stops being a hand-recorded snapshot:
 *
 *   tools/explore/cassini-moontilt.js    → rigidEllipse (torque-averaged,
 *                                          Brown/ELP i) + coupledAverage
 *                                          (real ELP orbit, 18.6 yr)
 *   tools/explore/moon-euler-rotation.js → eulerIntegration (full rigid-body
 *                                          rotation, no averaging assumption)
 *
 * Percentages are RECOMPUTED from the full-precision ε against the measured
 * 1.5424° (the Phase-1 decision — the previously published pcts were
 * rounded-input hand values). The inputs block (both lab scripts, the ELP
 * module, this generator) is verified by the artifact-freshness gate on
 * every `npm run check`.
 *
 *   node tools/verify/cassini-results.js            # run labs, print, compare
 *   node tools/verify/cassini-results.js --write    # + write the artifact
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const { ROOT, buildInputsBlock } = require('../lib/artifact-inputs');

const OUT = path.join(ROOT, 'data', 'cassini-moontilt-results.json');
const WRITE = process.argv.includes('--write');

const INPUT_FILES = [
  'tools/verify/cassini-results.js',
  'tools/explore/cassini-moontilt.js',
  'tools/explore/moon-euler-rotation.js',
  'tools/lib/elp2000-82b.js',
];

function runLab(rel) {
  console.log(`  running ${rel} ...`);
  const out = execFileSync('node', [path.join(ROOT, rel), '--json'],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
  const line = out.split('\n').find((l) => l.startsWith('@@CASSINI_JSON@@ '));
  if (!line) throw new Error(`${rel}: no @@CASSINI_JSON@@ result line in output`);
  return JSON.parse(line.slice('@@CASSINI_JSON@@ '.length));
}

const tilt = runLab('tools/explore/cassini-moontilt.js');
const euler = runLab('tools/explore/moon-euler-rotation.js');
if (tilt.measured !== euler.measured) {
  throw new Error(`labs disagree on the measured target: ${tilt.measured} vs ${euler.measured}`);
}
const measured = tilt.measured;
const section = (eps) => ({
  epsilonDeg: Number(eps.toFixed(4)),
  epsilonDegFull: eps,
  pctOfMeasured: Number((100 * eps / measured).toFixed(2)),
});

const artifact = {
  _description:
    'Cassini-state lunar obliquity lab results — GENERATED by ' +
    'tools/verify/cassini-results.js --write, which runs both labs live ' +
    '(cassini-moontilt.js: rigid-ellipse torque-averaged + coupled real-orbit ' +
    'average; moon-euler-rotation.js: full Euler integration, no averaging ' +
    'assumption). Percentages recomputed from full-precision epsilon against ' +
    'the measured 1.5424 deg. Consumed by the model-values registry ' +
    '(cassiniObliquity* keys); the inputs block is verified by the ' +
    'artifact-freshness gate on every npm run check.',
  measuredObliquityEclipticDeg: measured,
  rigidEllipse: section(tilt.rigidEllipse),
  coupledAverage: section(tilt.coupledAverage),
  eulerIntegration: section(euler.eulerIntegration),
  inputs: buildInputsBlock('node tools/verify/cassini-results.js --write', INPUT_FILES),
};

console.log('\n  measured             ε = %s°', measured);
for (const k of ['rigidEllipse', 'coupledAverage', 'eulerIntegration']) {
  console.log(`  ${k.padEnd(18)} ε = ${artifact[k].epsilonDeg}°  (${artifact[k].pctOfMeasured}% of measured)`);
}

if (fs.existsSync(OUT)) {
  const prev = JSON.parse(fs.readFileSync(OUT, 'utf8'));
  for (const k of ['rigidEllipse', 'coupledAverage', 'eulerIntegration']) {
    if (prev[k] && prev[k].epsilonDeg !== artifact[k].epsilonDeg) {
      console.log(`  NOTE ${k}: ε moved ${prev[k].epsilonDeg} → ${artifact[k].epsilonDeg}`);
    }
  }
}

if (WRITE) {
  fs.writeFileSync(OUT, JSON.stringify(artifact, null, 2) + '\n');
  console.log(`\n  ✓ wrote ${path.relative(ROOT, OUT)}`);
} else {
  console.log('\n  dry run — pass --write to update the artifact');
}

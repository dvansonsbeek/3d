#!/usr/bin/env python3
"""The zodiac band of date's external referee (plan 28 §F2, doc 111 §1.48): astropy's get_constellation.

Reads data/zodiac-boundary-reference.json (written by tools/pipeline/record-zodiac-boundaries.mjs --write from the
built scene: per epoch the ecliptic of date's pole and equinox as equatorial J2000 unit vectors, the one home's
crossings, and a sample every degree as J2000 α, δ with the solver's constellation), asks astropy's
`get_constellation` — Roman's (1987) algorithm on the same Delporte boundaries — for every sample, bisects
astropy's OWN boundary along the same ecliptic at every crossing, and writes the answers back into the record's
`astropy` block: the sample names, and per crossing astropy's longitude and its offset from the solver's.

The referee's model, named: get_constellation transforms the input to PrecessedGeocentric(equinox='B1875') — a
GEOCENTRIC frame at its default obstime (J2000.0), which carries the annual aberration (κ = 20.5″) on top of the
precession; the solver precesses alone (the boundaries are coordinate lines, and a line has no aberration). So
astropy's boundary sits up to ~21″ (0.006°) from the solver's, sinusoidally in longitude, and the gate pins the
offset at 25″ (measured here) — not at the boundaries' 1e-3° rounding. The constellation NAMES agree at every
sample.

CI's Python runner has no astropy, so the record is generated by hand; run it after record-zodiac-boundaries.

Usage: python3 scripts/zodiac_boundary_reference.py [--write]      (NOT python3 -I: isolated mode hides astropy)
"""
import json
import sys
from pathlib import Path

import astropy
import astropy.units as u
import numpy as np
from astropy.coordinates import SkyCoord, get_constellation

ROOT = Path(__file__).resolve().parent.parent
RECORD = ROOT / 'data' / 'zodiac-boundary-reference.json'


def names(points):
    if not points:
        return []
    c = SkyCoord(ra=[p['raDeg'] for p in points] * u.deg, dec=[p['decDeg'] for p in points] * u.deg, frame='icrs')
    return [str(n) for n in get_constellation(c, short_name=True)]


def frame_of(frame):
    """The ecliptic's own frame as the one home builds it: x the equinox projected into the plane, y = n × x."""
    n = np.array(frame['pole'], float); n /= np.linalg.norm(n)
    e0 = np.array(frame['equinox'], float); x = e0 - np.dot(n, e0) * n; x /= np.linalg.norm(x)
    return n, x, np.cross(n, x)


def name_at(fr, lon):
    n, x, y = fr
    a = np.radians(lon); v = x * np.cos(a) + y * np.sin(a)
    ra = np.degrees(np.arctan2(v[1], v[0])) % 360; dec = np.degrees(np.arcsin(v[2]))
    return str(get_constellation(SkyCoord(ra=ra * u.deg, dec=dec * u.deg, frame='icrs'), short_name=True))


def bisect_boundary(fr, lon0, half=0.05, iters=30):
    """astropy's boundary nearest a solver crossing: the longitude where its name changes, to 0.05° / 2^30."""
    lo, hi = lon0 - half, lon0 + half
    before, after = name_at(fr, lo), name_at(fr, hi)
    if before == after:
        return None, before, after
    for _ in range(iters):
        mid = (lo + hi) / 2
        if name_at(fr, mid) == before:
            lo = mid
        else:
            hi = mid
    return hi, before, after


def main():
    doc = json.loads(RECORD.read_text())
    out = {'version': astropy.__version__,
           'method': "astropy.coordinates.get_constellation(SkyCoord(ra, dec, frame='icrs'), short_name=True) — Roman 1987 on the IAU boundaries, the input transformed to PrecessedGeocentric(B1875) at obstime J2000.0 (the annual aberration included, ~20″); astropy's boundary per crossing bisected along the recorded ecliptic of date to 5e-11°",
           'epochs': []}
    total = agree = 0
    worst = 0.0
    for e in doc['epochs']:
        s = names(e['samples'])
        n_ok = sum(1 for a, b in zip(s, e['samples']) if a == b['abbr'])
        total += len(s); agree += n_ok
        fr = frame_of(e['frame'])
        bounds = []
        for c in e['crossings']:
            lon, before, after = bisect_boundary(fr, c['lonDeg'])
            off = None if lon is None else 3600 * (lon - c['lonDeg'])
            if off is not None:
                worst = max(worst, abs(off))
            bounds.append({'abbr': c['abbr'], 'solverLonDeg': c['lonDeg'], 'astropyLonDeg': lon, 'offsetArcsec': off, 'entered': after})
        out['epochs'].append({'label': e['label'], 'samples': s, 'boundaries': bounds})
        offs = [b['offsetArcsec'] for b in bounds if b['offsetArcsec'] is not None]
        print(f"{e['label']}: {n_ok}/{len(s)} samples agree; {len(bounds)} crossings, astropy's boundary offset {min(offs):+.1f} … {max(offs):+.1f} arcsec, names entered {''.join('✓' if b['entered'] == b['abbr'] else '✗' for b in bounds)}")
    out['worstOffsetArcsec'] = worst
    print(f"agreement {agree}/{total}; worst boundary offset {worst:.1f} arcsec")
    if '--write' in sys.argv:
        doc['astropy'] = out
        RECORD.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + '\n')
        print(f'wrote {RECORD.relative_to(ROOT)} (the astropy block)')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""The external referee of the sky of date's linear space motion (plan 28 §G (3); doc 111 §1.48).

astropy's SkyCoord.apply_space_motion (ERFA pmsafe — the rigorous space motion on the same
catalogue values: position, parallax, proper motion, radial velocity at the catalogue epoch)
for a few high-motion stars of the catalogue at ±10 kyr and ±100 kyr from J2000, written as a
RECORD the browser gate reads (test/browser/sky-of-date.test.mjs). The scene draws the plan's
straight line r = r₀ + v·Δt; the referee's rigorous model differs from it by its light-time
geometry on the transverse path — MEASURED (doc 111 §1.48): nothing for a star without proper
motion, unchanged by the radial velocity, ten times larger at ten times the distance for the same
angular motion; 0.3″ at 10 kyr and 0.4″ at 100 kyr for Sirius, 2″ and 54″ for Groombridge 1830.
The plan's 1″ / 10″ holds for Sirius, Arcturus and α Centauri; the two fastest stars are pinned
at their measured gap (TOLERANCES below, the measurement rounded up) — a regression pin that a
wrong unit or sign fails by degrees, not a claim of agreement with the rigorous model, which is
named open.

The stars: Sirius (HIP 32349), Arcturus (69673), α Centauri A (71683), 61 Cygni A (104214) and
Groombridge 1830 (57939) — the plan named Barnard's star, which at V 9.5 is outside the V ≤ 8
catalogue; the two high-proper-motion naked-eye stars stand in its place.

Usage: python3 scripts/star_motion_reference.py [--write]
  Reads public/input/stars.json (v2) and prints the reference; --write records it to
  data/star-motion-reference.json with the catalogue's canonical sha256 as its input.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STARS = os.path.join(ROOT, 'public', 'input', 'stars.json')
OUT = os.path.join(ROOT, 'data', 'star-motion-reference.json')
HIPS = [32349, 69673, 71683, 104214, 57939]
YEARS = [2000.0, 12000.0, -8000.0, 102000.0, -98000.0]
# arcseconds at ±10 kyr and ±100 kyr: the plan's 1 / 10 where the measurement allows, the measured
# light-time gap rounded up where it does not (61 Cyg A 1.0 / 17 ″, Groombridge 1830 2.0 / 59 ″)
TOLERANCES = {32349: (1.0, 10.0), 69673: (1.0, 10.0), 71683: (1.0, 10.0), 104214: (2.0, 20.0), 57939: (3.0, 65.0)}


def main(write):
    import astropy.units as u
    from astropy.coordinates import SkyCoord
    from astropy.time import Time

    with open(STARS, 'rb') as f:
        raw = f.read()
    doc = json.loads(raw)
    ci = {c: i for i, c in enumerate(doc['columns'])}
    rows = {r[ci['hip']]: r for r in doc['stars']}
    epoch = doc['_meta']['epochYear']
    out = {}
    for hip in HIPS:
        r = rows[hip]
        rv = r[ci['rvKmS']]
        d_pc = r[ci['distPc']]
        c = SkyCoord(ra=r[ci['raDeg']] * u.deg, dec=r[ci['decDeg']] * u.deg, distance=d_pc * u.pc,
                     pm_ra_cosdec=r[ci['pmRaMasYr']] * u.mas / u.yr, pm_dec=r[ci['pmDecMasYr']] * u.mas / u.yr,
                     radial_velocity=(rv if rv is not None else 0.0) * u.km / u.s,
                     frame='icrs', obstime=Time(epoch, format='jyear', scale='tdb'))
        per = []
        for y in YEARS:
            # the TDB scale: a UTC year far from today has no leap-second table (ERFA taiutc refuses it);
            # the span between two Julian epochs is what the motion needs, and TDB carries it at every year
            c2 = c.apply_space_motion(new_obstime=Time(y, format='jyear', scale='tdb'))
            per.append({'year': y, 'raDeg': float(c2.ra.deg), 'decDeg': float(c2.dec.deg), 'distPc': float(c2.distance.pc)})
        out[str(hip)] = {'name': (doc.get('names', {}).get(str(hip), {}) or {}).get('name'), 'rvKmS': rv, 'distFlag': r[ci['distFlag']],
                         'toleranceArcsec': {'10kyr': TOLERANCES[hip][0], '100kyr': TOLERANCES[hip][1]}, 'positions': per}
    sha = hashlib.sha256(raw).hexdigest()
    rec = {
        '_description': 'The external referee of the sky of date (plan 28 §G (3)) — GENERATED by scripts/star_motion_reference.py --write: astropy SkyCoord.apply_space_motion (ERFA pmsafe) on the catalogue values of five high-motion stars at ±10 kyr and ±100 kyr from J2000. The browser gate test/browser/sky-of-date.test.mjs reads it: the scene (the straight line) within each star\'s toleranceArcsec — the plan\'s 1 / 10 arcsec for Sirius, Arcturus and alpha Centauri; the measured light-time gap of the rigorous model, rounded up, for the two fastest stars (doc 111 section 1.48).',
        'generated_by': 'python3 scripts/star_motion_reference.py --write',
        'inputs': {'public/input/stars.json': {'sha256': sha, 'epochYear': epoch, 'counts': doc['_meta']['counts']}},
        'tolerancesArcsec': {'10kyr': 1.0, '100kyr': 10.0},
        'stars': out,
    }
    text = json.dumps(rec, indent=1) + '\n'
    if write:
        with open(OUT, 'w') as f:
            f.write(text)
        print('wrote', os.path.relpath(OUT, ROOT))
    else:
        print(text)


if __name__ == '__main__':
    main('--write' in sys.argv[1:])
